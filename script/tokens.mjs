#!/usr/bin/env node
// Generates each platform's theme files from design/tokens.json.
//
//   node script/tokens.mjs           write the files
//   node script/tokens.mjs --check   exit 1 if any file is out of date
//   node --test script/              the generator's own tests
//
// Outputs (the website keeps its own palette, in web/src/site/site-tokens.css):
//   ios/DeptheosMobile/Assets.xcassets/AccentColor    the iOS tint; everything else stays system
//   ios/DeptheosMobile/Assets.xcassets/Viewer         the photo backdrop
//   ios/DeptheosMobile/Assets.xcassets/AccentFill     the one primary button (Stack)
//   ios/DeptheosMobile/Assets.xcassets/Edited         the dot that marks edited
//   ios/DeptheosMobile/Assets.xcassets/Hud*           chrome over the photo (fill, border, text)
//   crates/deptheos_gpui/themes/deptheos.json         gpui-kit light and dark themes
//   crates/deptheos_gpui/themes/deptheos-p3.json      the same in Display P3, for a wide-gamut screen
//   crates/deptheos_gpui/src/brand.rs                 colors the desktop app paints itself, in both spaces

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const MODES = ["light", "dark"];
const HEADER = "Generated by script/tokens.mjs from design/tokens.json. Do not edit.";

// Throws on a token file the generator can't use. A color is #rrggbb, or
// #rrggbbaa where it is see-through (only the desktop's own colors, in
// brand.rs, may be). The photo backdrop and the chrome over the photo
// (`viewer`, `hud*`) are one value in both modes: the desktop reads one,
// and what sits over a photo shouldn't change with the window's mode.
export function validate(tokens) {
  const c = tokens.color;
  for (const [name, t] of Object.entries(c)) {
    for (const m of MODES) {
      if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/.test(t[m])) {
        throw new Error(`color.${name}.${m} must be #rrggbb or #rrggbbaa lowercase, got ${t[m]}`);
      }
    }
  }
  for (const name of Object.keys(c).filter((n) => n === "viewer" || n.startsWith("hud"))) {
    if (c[name].light !== c[name].dark) throw new Error(`color.${name}.light and .dark must be equal`);
  }
  for (const name of ["hud", "hud-border", "hud-text"]) {
    if (!c[name]) throw new Error(`color.${name} is missing`);
  }
}

// sRGB to Display P3, both D65, on linear values.
const SRGB_TO_P3 = [
  [0.822461968714, 0.177538031286, 0],
  [0.03319419885, 0.96680580115, 0],
  [0.017082630603, 0.072397440673, 0.910519928724],
];

// #rrggbb or #rrggbbaa, an sRGB color, as the same color in Display P3:
// decoded, through the matrix, encoded with sRGB's curve (P3 shares it)
// and rounded to 8 bits; the alpha is kept and grays come out as they went in.
export function toDisplayP3(hex) {
  const decode = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  const encode = (c) => (c <= 0.0031308 ? c * 12.92 : 1.055 * c ** (1 / 2.4) - 0.055);
  const linear = [1, 3, 5].map((i) => decode(parseInt(hex.slice(i, i + 2), 16) / 255));
  const p3 = SRGB_TO_P3.map((row) => row.reduce((sum, m, i) => sum + m * linear[i], 0));
  const byte = (c) => Math.round(Math.min(1, Math.max(0, encode(c))) * 255).toString(16).padStart(2, "0");
  return `#${p3.map(byte).join("")}${hex.slice(7)}`;
}

// Only when run, not when the tests import `validate`.
if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) generate();

function generate() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));
  validate(tokens);
  const c = tokens.color;

  // ---- iOS ----
  function iosColor(hex) {
    if (hex.length !== 7 && hex.length !== 9) throw new Error(`iOS colors must be #rrggbb or #rrggbbaa, got ${hex}`);
    const [r, g, b] = [1, 3, 5].map((i) => hex.slice(i, i + 2).toUpperCase());
    const alpha = hex.length === 9 ? (parseInt(hex.slice(7, 9), 16) / 255).toFixed(3) : "1.000";
    return { "color-space": "srgb", components: { alpha, red: `0x${r}`, green: `0x${g}`, blue: `0x${b}` } };
  }
  const info = { author: "xcode", version: 1 };
  const iosCatalog = JSON.stringify({ info }, null, 2) + "\n";
  const iosAccent = JSON.stringify({
    colors: [
      { color: iosColor(c.accent.light), idiom: "universal" },
      { appearances: [{ appearance: "luminosity", value: "dark" }], color: iosColor(c.accent["ios-dark"] ?? c.accent.dark), idiom: "universal" },
    ],
    info,
  }, null, 2) + "\n";

  // A color set of one token, light and dark.
  function iosColorSet(token) {
    return JSON.stringify({
      colors: [
        { color: iosColor(token.light), idiom: "universal" },
        { appearances: [{ appearance: "luminosity", value: "dark" }], color: iosColor(token.dark), idiom: "universal" },
      ],
      info,
    }, null, 2) + "\n";
  }
  const iosViewer = iosColorSet(c.viewer);

  // ---- Desktop (gpui-kit) ----
  // gpui-kit fills any key a theme leaves out with its own stock grays, so most
  // keys are set here to keep the surfaces in one family. A suffix after the
  // token name is a hex alpha byte (29 = 16 %, 33 = 20 %, 40 = 25 %, 80 = 50 %);
  // a literal #rrggbb is used as is.
  const gpuiMap = {
    "background": "background",
    "foreground": "text",
    "border": "line",
    "input.border": "control-border",
    "window.border": "line",
    "title_bar.background": "background",
    "title_bar.border": "line",
    "status_bar.background": "surface",
    "status_bar.border": "line",
    "muted.background": "surface-sunken",
    "muted.foreground": "text-muted",
    "primary.background": "accent-fill",
    "primary.foreground": "on-accent-fill",
    "secondary.background": "surface-sunken",
    "secondary.hover.background": "surface-hover",
    "secondary.active.background": "surface-active",
    "secondary.foreground": "text",
    "accent.background": "surface-active",
    "accent.foreground": "text",
    "popover.background": "surface",
    "popover.foreground": "text",
    "group_box.background": "surface-sunken",
    "group_box.foreground": "text",
    "list.background": "surface",
    "list.even.background": "surface",
    "list.head.background": "surface-sunken",
    "list.hover.background": "surface-hover",
    "list.active.background": "accent 29",
    "list.active.border": "accent",
    "table.background": "surface",
    "table.even.background": "surface",
    "table.head.background": "surface-sunken",
    "table.head.foreground": "text-muted",
    "table.hover.background": "surface-hover",
    "table.active.background": "accent 29",
    "table.active.border": "accent",
    "table.row.border": "line",
    "sidebar.background": "surface",
    "sidebar.foreground": "text",
    "sidebar.border": "line",
    "sidebar.accent.background": "surface-hover",
    "sidebar.accent.foreground": "text",
    "sidebar.primary.background": "accent",
    "sidebar.primary.foreground": "on-accent",
    "tab_bar.background": "surface-sunken",
    "tab_bar.segmented.background": "surface-sunken",
    "tab.background": "surface-sunken",
    "tab.foreground": "text-segment",
    "tab.active.background": "surface",
    "tab.active.foreground": "text",
    "skeleton.background": "surface-sunken",
    "scrollbar.thumb.background": "text-muted 80",
    "scrollbar.thumb.hover.background": "text-muted",
    "switch.background": "control-border",
    "slider.background": "accent",
    "slider.thumb.background": "#ffffff",
    "switch.thumb.background": "#ffffff",
    "progress.bar.background": "accent",
    "ring": "accent",
    "caret": "accent",
    "selection.background": "accent 40",
    "drag.border": "accent",
    "drop_target.background": "accent 33",
    "link": "accent",
    "link.hover": "accent",
    "link.active": "accent",
    "info.background": "accent",
    "success.background": "success",
    "warning.background": "warning",
    "danger.background": "danger",
    "base.blue": "accent",
    "base.green": "success",
    "base.yellow": "warning",
    "base.red": "danger",
  };
  // The colors in sRGB, or through `space` (toDisplayP3).
  function gpuiColors(mode, space) {
    const out = {};
    for (const [key, ref] of Object.entries(gpuiMap)) {
      if (ref.startsWith("#")) { out[key] = space(ref); continue; }
      const [name, alpha = ""] = ref.split(" ");
      if (!c[name]) throw new Error(`gpui key ${key} names unknown token ${name}`);
      if (alpha && c[name][mode].length !== 7) throw new Error(`gpui key ${key} adds an alpha to see-through ${name}`);
      out[key] = space(c[name][mode] + alpha);
    }
    return out;
  }
  const gpuiTheme = (space) => JSON.stringify({
    $comment: HEADER,
    name: "Deptheos",
    author: "Deptheos",
    themes: MODES.map((mode) => ({
      is_default: true,
      name: `Deptheos ${mode === "light" ? "Light" : "Dark"}`,
      mode,
      radius: tokens.radius.md.value,
      "radius.lg": tokens.radius.lg.value,
      colors: gpuiColors(mode, space),
    })),
  }, null, 2) + "\n";
  const asIs = (h) => h;

  // ---- Desktop: colors painted outside gpui-kit's components ----
  const hex = (h) => {
    if (h.length !== 7) throw new Error(`expected an opaque color, got ${h}`);
    return `0x${h.slice(1)}`;
  };
  // #rrggbb or #rrggbbaa as 0xrrggbbaa, opaque when no alpha is given.
  const rgba = (h) => `0x${h.slice(1)}${h.length === 7 ? "ff" : ""}`;
  const brand = (space) => `Brand {
    viewer_background: ${hex(space(c.viewer.dark))},
    accent_on_photo: ${hex(space(c.accent.dark))},
    edited: [${hex(space(c.edited.light))}, ${hex(space(c.edited.dark))}],
    hud: ${rgba(space(c.hud.dark))},
    hud_border: ${rgba(space(c["hud-border"].dark))},
    hud_text: ${rgba(space(c["hud-text"].dark))},
}`;
  const brandRs = `// ${HEADER}
//! Brand colors the app paints itself, outside gpui-kit's themed components,
//! in sRGB and in Display P3 (\`crate::color::brand\` picks the screen's).

/// The colors, in one space.
pub struct Brand {
    /// The photo backdrop: neutral and dark in both modes, so photos read true.
    pub viewer_background: u32,
    /// The accent's light form, for marks drawn over a photo.
    pub accent_on_photo: u32,
    /// The dot that marks edited, in light and dark mode.
    pub edited: [u32; 2],
    /// Chrome over the photo, the same in both modes, as RGBA
    /// (\`gpui::rgba\`): its fill, its edge and its text.
    pub hud: u32,
    pub hud_border: u32,
    pub hud_text: u32,
}

pub const SRGB: Brand = ${brand(asIs)};

pub const DISPLAY_P3: Brand = ${brand(toDisplayP3)};
`;

  // ---- Write or check ----
  const outputs = {
    "ios/DeptheosMobile/Assets.xcassets/Contents.json": iosCatalog,
    "ios/DeptheosMobile/Assets.xcassets/AccentColor.colorset/Contents.json": iosAccent,
    "ios/DeptheosMobile/Assets.xcassets/Viewer.colorset/Contents.json": iosViewer,
    "ios/DeptheosMobile/Assets.xcassets/AccentFill.colorset/Contents.json": iosColorSet(c["accent-fill"]),
    "ios/DeptheosMobile/Assets.xcassets/Edited.colorset/Contents.json": iosColorSet(c.edited),
    "ios/DeptheosMobile/Assets.xcassets/Hud.colorset/Contents.json": iosColorSet(c.hud),
    "ios/DeptheosMobile/Assets.xcassets/HudBorder.colorset/Contents.json": iosColorSet(c["hud-border"]),
    "ios/DeptheosMobile/Assets.xcassets/HudText.colorset/Contents.json": iosColorSet(c["hud-text"]),
    "crates/deptheos_gpui/themes/deptheos.json": gpuiTheme(asIs),
    "crates/deptheos_gpui/themes/deptheos-p3.json": gpuiTheme(toDisplayP3),
    "crates/deptheos_gpui/src/brand.rs": brandRs,
  };
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, content] of Object.entries(outputs)) {
    const path = join(root, rel);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) continue;
    if (check) {
      console.error(`out of date: ${rel}`);
      stale++;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote ${rel}`);
    }
  }
  if (check && stale) {
    console.error("Run `node script/tokens.mjs` and commit the result.");
    process.exit(1);
  }
}
